def runtime_directory(root):
    from resting_eeg.data.paths import load_paths
    return load_paths(root)['runtime_root']/'batches'


def frozen_hashes(root):
    p = paths(root)
    _, pre = load_config(p['config_path'])
    _, access = load_access_config(p['access_config_path'], p['config_path'])
    if pre != FROZEN_SHA or access != ACCESS_SHA:
        raise ValueError('Frozen scientific configuration changed')
    config = Path(root)/'configs/streaming/batched_streaming_v1.yaml'
    digest = sha256_file(config)
    if config.with_suffix('.sha256').read_text().strip() != digest:
        raise ValueError('Variable batch config checksum mismatch')
    policy = yaml.safe_load(config.read_text())
    if policy['batch_size_policy']['gibibyte_bytes'] != GIB:
        raise ValueError('Invalid GiB unit')
    return dict(preprocessing_config_sha256=pre, mechanical_access_config_sha256=access,
                variable_batch_config_sha256=digest)


def plan_membership(frame, cap, completed=(), assigned=()):
    if not isinstance(cap, int) or isinstance(cap, bool) or cap <= 0:
        raise ValueError('Positive integer cap required')
    # Validates pairs, paths, hashes, URL allowlist, and duplicate assets.
    st._manifest_rows(frame, Path('synthetic_manifest_validation'))
    excluded = set(completed) | set(assigned)
    members, total, next_subject = [], 0, None
    for subject, group in frame.groupby('subject_id', sort=False):
        if subject in excluded:
            continue
        size = sum(int(v) for v in group.payload_size_bytes)
        if size > cap:
            raise ValueError(f'Single subject {subject} payload {size} exceeds cap {cap}')
        if total + size > cap:
            next_subject = dict(subject_id=subject, declared_bytes=size,
                                reason='next_subject_would_exceed_batch_cap')
            break
        members.append(dict(subject_id=subject, declared_bytes=size, asset_count=len(group)))
        total += size
    if not members:
        raise ValueError('No unassigned incomplete subjects fit this batch')
    ids = [r['subject_id'] for r in members]
    selected = pd.concat([frame.loc[frame.subject_id == subject] for subject in ids], ignore_index=True)
    return selected, dict(subject_ids=ids, subjects=members, subject_count=len(ids), asset_count=len(selected),
        cap_bytes=cap, cap_gib=cap/GIB, declared_bytes=total, declared_gib=total/GIB,
        unused_capacity_bytes=cap-total, unused_capacity_gib=(cap-total)/GIB,
        first_not_included=next_subject)


def verified_completed(root):
    p = paths(root)
    complete = []
    journals = [runtime_directory(root).parent/'streaming_all_block_status.jsonl']
    journals += list(runtime_directory(root).glob('*_streaming_journal.jsonl'))
    history = [r for path in journals for r in read_journal(path)]
    for file in sorted(p['output_root'].glob('*_all_blocks.h5')):
        subject = file.name.removesuffix('_all_blocks.h5')
        receipt = read_json(file.with_suffix('.provenance.json'))
        st._verify_receipt(receipt, subject, p['config_path'], p['output_root'])
        blocks = ab.expected_subject_blocks(root, subject)
        if receipt['authoritative_blocks'] != blocks:
            raise ValueError(f'Authoritative blocks differ: {subject}')
        if not any(r.get('subject_id') == subject and r.get('status') == 'complete'
                   and r.get('result', {}).get('output_sha256') == receipt['output_sha256'] for r in history):
            raise ValueError(f'Completed output lacks durable journal: {subject}')
        complete.append(subject)
    return complete


def ledger_read(directory):
    file = directory/'batch_ledger.json'
    return read_json(file) if file.exists() else {'schema_version': 1, 'batches': []}


def verify_frozen(directory, batch_id, manifest_path=None, requested_cap=None):
    name = batch_name(batch_id)
    ledger = ledger_read(directory)
    entries = [e for e in ledger['batches'] if e['batch_id'] == batch_id]
    if len(entries) != 1 or entries[0]['batch_status'] not in {'frozen', 'executing', 'complete', 'failed_or_partial'}:
        raise ValueError('Batch is not frozen')
    entry = entries[0]
    manifest = directory/f'{name}_manifest.csv'
    if manifest_path is not None and Path(manifest_path).resolve() != manifest.resolve():
        raise ValueError('Execution must use the frozen manifest path')
    if requested_cap is not None and requested_cap != entry['cap_bytes']:
        raise ValueError('Frozen batch cap cannot change')
    if sha256_file(manifest) != entry['manifest_sha256']:
        raise ValueError('Frozen batch membership/manifest changed')
    plan = read_json(directory/f'{name}_plan.json')
    if canonical_hash(plan) != entry['plan_sha256']:
        raise ValueError('Frozen batch plan/cap changed')
    if entry.get('plan_file_sha256') and sha256_file(directory/f'{name}_plan.json') != entry['plan_file_sha256']:
        raise ValueError('Frozen plan file changed')
    frame = pd.read_csv(manifest)
    ids = frame.subject_id.drop_duplicates().tolist()
    if ids != plan['subject_ids'] or plan['cap_bytes'] != entry['cap_bytes']:
        raise ValueError('Frozen order or cap mismatch')
    if int(frame.payload_size_bytes.sum()) != plan['declared_bytes'] or plan['declared_bytes'] > plan['cap_bytes']:
        raise ValueError('Frozen declared accounting mismatch')
    return frame, plan, entry


def freeze_batch(directory, batch_id, cap, frame, completed, head, hashes):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    name = batch_name(batch_id)
    with st._journal_lock(directory/'batch_ledger'):
        ledger = ledger_read(directory)
        if any(e['batch_id'] == batch_id for e in ledger['batches']):
            existing, plan, _ = verify_frozen(directory, batch_id, requested_cap=cap)
            # Rerun never recalculates membership from mutable completion/local state.
            authoritative = frame.loc[frame.subject_id.isin(plan['subject_ids'])].reset_index(drop=True)
            if authoritative.to_dict('records') != existing.to_dict('records'):
                raise ValueError('Authoritative frozen membership changed')
            return plan
        assigned = []
        for old in ledger['batches']:
            _, old_plan, _ = verify_frozen(directory, old['batch_id'])
            assigned += old_plan['subject_ids']
        if len(assigned) != len(set(assigned)):
            raise ValueError('Subjects duplicated across batches')
        if int(batch_id) != len(ledger['batches']) + 1:
            raise ValueError('Only the next sequential batch may be frozen')
        selected, plan = plan_membership(frame, cap, completed, assigned)
        plan.update(batch_id=batch_id, frozen_at_utc=utc_now(), authorization_head=head,
                    excluded_verified_completed=list(completed), **hashes)
        manifest = directory/f'{name}_manifest.csv'
        if manifest.exists() or (directory/f'{name}_plan.json').exists():
            raise ValueError('Incomplete freeze transaction: preserve and investigate existing artifacts')
        csv_write(manifest, selected)
        write_json(directory/f'{name}_plan.json', plan)
        ledger['batches'].append(dict(batch_id=batch_id, batch_status='frozen', cap_bytes=cap,
            cap_gib=cap/GIB, manifest_path=str(manifest.resolve()), manifest_sha256=sha256_file(manifest),
            plan_sha256=canonical_hash(plan), plan_file_sha256=sha256_file(directory/f'{name}_plan.json'),
            subject_count=plan['subject_count'], declared_bytes=plan['declared_bytes'],
            authorization_head=head, authorization_time_utc=plan['frozen_at_utc'],
            execution_started=None, execution_completed=None))
        write_json(directory/'batch_ledger.json', ledger)
        return plan


def update_ledger(directory, batch_id, **changes):
    with st._journal_lock(directory/'batch_ledger'):
        ledger = ledger_read(directory)
        entry = next(e for e in ledger['batches'] if e['batch_id'] == batch_id)
        if set(changes) - {'batch_status', 'execution_started', 'execution_completed'}:
            raise ValueError('Immutable ledger fields cannot change')
        entry.update(changes)
        write_json(directory/'batch_ledger.json', ledger)


def verify_previous_state(root, batch_id, *, full=False):
    """Preserve prior completions under a separately authorized batch boundary."""
    if int(batch_id) < 2:
        return None
    directory = paths(root)['metrics_root']/'batches'
    baseline = directory/f'{batch_name(batch_id)}_starting_state.json'
    before = read_json(baseline)
    previous = before.get('prior_ledger_entries')
    if previous is None:  # Original Batch 002 baseline stays byte-identical.
        previous = [before['batch_001_ledger_entry']]
    if len(previous) != int(batch_id)-1 or ledger_read(directory)['batches'][:len(previous)] != previous:
        raise ValueError('Prior batch ledger changed')
    for record in before['files']:
        file = Path(record['path'])
        # Full payload preservation is rehashed at authorization and acceptance;
        # small prior records and frozen scientific source are checked per subject.
        if full or record['bytes'] < 1024*1024:
            if not file.is_file() or sha256_file(file) != record['sha256']:
                raise ValueError(f'Prior completed artifact changed: {file}')
    for name, evidence in before['registries'].items():
        rows = pd.read_csv(paths(root)['metrics_root']/name).fillna('')
        prior = rows.loc[rows.subject_id.isin(before['completed_subjects'])].to_dict('records')
        if len(prior) != evidence['count'] or canonical_hash(prior) != evidence['sha256']:
            raise ValueError(f'Prior access registry changed: {name}')
    next_id = f'{int(batch_id)+1:03}'
    if any(directory.glob(f'batch_{next_id}*')) or any(int(e['batch_id']) > int(batch_id) for e in ledger_read(directory)['batches']):
        raise ValueError(f'Batch {next_id} is prohibited during Batch {batch_id}')
    if any(runtime_directory(root).glob(f'batch_{next_id}*')):
        raise ValueError(f'Batch {next_id} runtime record is prohibited')
    return sha256_file(baseline)


def network_preflight(frame, plan, raw_root, output_root):
    from resting_eeg.data.environment import system_drive_guard
    system_drive = system_drive_guard('batch_network_preflight')
    verified = partial = 0
    prefixes = []
    remaining_by_subject = {}
    for row, target in st._manifest_rows(frame, raw_root):
        size = int(row['payload_size_bytes'])
        remaining = size
        part = target.with_name(target.name + '.part')
        st._assert_no_links(part)
        if target.exists() and part.exists():
            raise ValueError('Conflicting complete payload and partial transaction')
        if target.exists():
            st.downloader.verify_file(target, size, str(row['payload_sha256']))
            verified += size
            remaining = 0
        else:
            if part.exists() and part.stat().st_size > size:
                raise ValueError('Partial exceeds declared payload; preserve and investigate')
            if part.exists() and 0 < part.stat().st_size <= size:
                if part.stat().st_size == size:
                    st.downloader.verify_file(part, size, str(row['payload_sha256']))
                # Incomplete prefixes cannot be SHA-verified against a whole-file
                # digest. These are resumable lengths; final SHA remains mandatory.
                partial += part.stat().st_size
                remaining -= part.stat().st_size
                prefixes.append(dict(relative_path=str(row['relative_path']), bytes=part.stat().st_size,
                                     prefix_sha256=sha256_file(part), whole_file_sha_verified=part.stat().st_size == size))
        subject = row['subject_id']
        remaining_by_subject[subject] = remaining_by_subject.get(subject, 0) + remaining
    declared = int(frame.payload_size_bytes.sum())
    largest = max((int(g.payload_size_bytes.sum()) for _, g in frame.groupby('subject_id', sort=False)), default=0)
    compact = plan['subject_count'] * st.COMPACT_OUTPUT_ALLOWANCE_BYTES
    free = st._free_bytes(raw_root)
    # Network membership never becomes a simultaneous disk reservation. Retained
    # raw already occupies disk and is therefore already deducted from free space.
    # The unchanged dynamic subject guard checks again as retained failures grow.
    retained = directory_bytes(raw_root)
    required = max(remaining_by_subject.values(), default=0) + st.PROCESSING_OVERHEAD_BYTES + st.COMPACT_OUTPUT_ALLOWANCE_BYTES + st.SAFETY_MARGIN_BYTES
    report = dict(batch_id=plan['batch_id'], cap_bytes=plan['cap_bytes'], declared_bytes=declared,
        cap_gib=plan['cap_bytes']/GIB, declared_gib=declared/GIB,
        subject_count=plan['subject_count'], subject_ids=plan['subject_ids'],
        unused_capacity_bytes=plan['cap_bytes']-declared, system_drive=system_drive,
        verified_existing_bytes=verified, valid_partial_bytes=partial,
        partial_prefixes=prefixes, expected_new_network_bytes=declared-verified-partial,
        largest_subject_bytes=largest, processing_overhead_bytes=st.PROCESSING_OVERHEAD_BYTES,
        expected_compact_output_bytes=compact, compact_estimate_basis='conservative 32 MiB per subject including temporary allowance',
        retained_raw_bytes=retained, remaining_payload_bytes_by_subject=remaining_by_subject,
        maximum_one_subject_temporary_requirement_bytes=required,
        peak_footprint_including_retained_raw_bytes=retained+required,
        retained_raw_accounting='Already occupied; included in footprint, already deducted from current free space.',
        disk_policy='one_subject_at_a_time_dynamic_guard',
        free_disk_bytes=free, required_free_bytes=required,
        disk_ok=free >= required and st._free_bytes(output_root) >= st.COMPACT_OUTPUT_ALLOWANCE_BYTES + st.SAFETY_MARGIN_BYTES,
        created_utc=utc_now(), partial_note='Resumable incomplete prefixes are unverified until final whole-file SHA256; server may ignore Range.',
        traffic_note='Expected response payload excludes retries, ignored Range, and unmeasured HTTP/TLS/ISP overhead.')
    if declared > plan['cap_bytes'] or not report['disk_ok']:
        raise ValueError('Batch cap or disk guard failed')
    return report


def print_preflight(report):
    print(f"BATCH {report['batch_id']} NETWORK PREFLIGHT", flush=True)
    for label, key in [('Cap', 'cap_bytes'), ('Declared payload', 'declared_bytes'),
                       ('Expected new transfer', 'expected_new_network_bytes'), ('Verified existing', 'verified_existing_bytes'),
                       ('Valid partial', 'valid_partial_bytes'), ('Free disk', 'free_disk_bytes'), ('Largest subject', 'largest_subject_bytes'),
                       ('Maximum one-subject free-space need', 'required_free_bytes'), ('Retained raw', 'retained_raw_bytes')]:
        print(f'{label}: {report[key]/GIB:.4f} GiB', flush=True)
    print(f"Subjects: {report['subject_count']}\nExpected compact output: {report['expected_compact_output_bytes']/1024**2:.2f} MiB", flush=True)


def authorize(root, batch_id, directory, manifest_path=None, requested_cap=None):
    from resting_eeg.data.paths import load_paths
    p = paths(root)
    head = require_committed_clean(root)
    hashes = frozen_hashes(root)
    frame, plan, entry = verify_frozen(directory, batch_id, manifest_path, requested_cap)
    prior_hash = verify_previous_state(root, batch_id, full=True)
    if int(batch_id) >= 2:
        before = read_json(directory/f'{batch_name(batch_id)}_starting_state.json')
        approved_cap = before.get('authorized_cap_bytes', 10*GIB if batch_id=='002' else None)
        if approved_cap is None or plan['cap_bytes'] != approved_cap or set(plan['subject_ids']) & set(before['completed_subjects']):
            raise ValueError(f'Batch {batch_id} cap or prior completion exclusion violated')
    if any(plan[k] != v for k, v in hashes.items()):
        raise ValueError('Frozen config differs from plan')
    report = network_preflight(frame, plan, p['raw_root'], p['output_root'])
    report.update(manifest_sha256=entry['manifest_sha256'], plan_sha256=entry['plan_sha256'],
                  plan_file_sha256=sha256_file(directory/f'{batch_name(batch_id)}_plan.json'), **hashes)
    print_preflight(report)
    name = batch_name(batch_id)
    preflight_file = directory/f'{name}_network_preflight.json'
    auth_file = directory/f'{name}_execution_authorization.json'
    if auth_file.exists():
        auth = read_json(auth_file)
        if auth['authorization_code_head'] != head:
            raise ValueError('Code HEAD changed: explicitly archive authorization before superseding it')
        validate_authorization(root, batch_id, directory)
        return auth
    write_json(preflight_file, report)
    auth = dict(batch_id=batch_id, cap_bytes=plan['cap_bytes'], cap_gib=plan['cap_gib'],
        subject_ids=plan['subject_ids'], declared_bytes=plan['declared_bytes'], manifest_sha256=entry['manifest_sha256'],
        plan_sha256=entry['plan_sha256'], **hashes, authorization_code_head=head,
        expected_new_network_bytes=report['expected_new_network_bytes'], authorization_utc=utc_now(),
        permission=f'Execute Batch {batch_id} ONLY; no future batch planning or execution authorized by this record.',
        prohibit_batch_002_during_this_assignment=batch_id == '001',
        prohibited_next_batch_id=f'{int(batch_id)+1:03}',
        prior_state_sha256=prior_hash,
        network_preflight_sha256=sha256_file(preflight_file),
        resolved_paths={k:str(v) for k,v in p.items()},
        plan_file_sha256=report['plan_file_sha256'],
        verified_existing_bytes=report['verified_existing_bytes'], valid_partial_bytes=report['valid_partial_bytes'],
        partial_prefixes=report['partial_prefixes'], system_drive=report['system_drive'], free_disk_bytes=report['free_disk_bytes'],
        storage_roots={k:str(v) for k,v in load_paths(root).items()})
    write_json(auth_file, auth)
    return auth


def validate_authorization(root, batch_id, directory):
    frame, plan, entry = verify_frozen(directory, batch_id)
    auth = read_json(directory/f'{batch_name(batch_id)}_execution_authorization.json')
    if int(batch_id) >= 2 and auth.get('prior_state_sha256') != verify_previous_state(root, batch_id):
        raise ValueError('Prior-state authorization checksum changed')
    for key in ('cap_bytes', 'declared_bytes', 'subject_ids', 'batch_id'):
        if auth[key] != plan[key]:
            raise ValueError(f'Authorization mismatch: {key}')
    for key in ('manifest_sha256', 'plan_sha256'):
        if auth[key] != entry[key]:
            raise ValueError(f'Authorization mismatch: {key}')
    if any(auth[k] != v for k, v in frozen_hashes(root).items()):
        raise ValueError('Authorization configuration mismatch')
    if auth['resolved_paths'] != {k:str(v) for k,v in paths(root).items()}:
        raise ValueError('Authorized storage paths changed')
    if auth['network_preflight_sha256'] != sha256_file(directory/f'{batch_name(batch_id)}_network_preflight.json'):
        raise ValueError('Authorized network preflight changed')
    base_path = directory/f'{batch_name(batch_id)}_execution_authorization.json'
    for resume_path in sorted(directory.glob(f'{batch_name(batch_id)}_resume_authorization_*.json')):
        resumed = read_json(resume_path)
        if resumed['original_authorization_sha256'] != sha256_file(base_path):
            raise ValueError('Original authorization changed after interruption')
        for key in ('cap_bytes','declared_bytes','subject_ids','batch_id','manifest_sha256','plan_sha256',
                    'preprocessing_config_sha256','mechanical_access_config_sha256','variable_batch_config_sha256',
                    'resolved_paths','expected_new_network_bytes','network_preflight_sha256'):
            if resumed[key] != auth[key]:
                raise ValueError(f'Resume authorization changed frozen evidence: {key}')
        auth = resumed
    return frame, plan, auth


def authorize_resume(root, batch_id, directory, *, network_policy=None):
    """Supersede execution code only; preserve original authorization and freeze."""
    from resting_eeg.data.environment import configure_environment
    head=require_committed_clean(root)
    frame,plan,previous=validate_authorization(root,batch_id,directory)
    environment=configure_environment(root)
    completed=verified_completed(root)
    remaining=frame.loc[~frame.subject_id.isin(completed)].copy()
    remaining_ids=remaining.subject_id.drop_duplicates().tolist()
    remaining_plan=dict(plan,subject_count=len(remaining_ids),subject_ids=remaining_ids)
    report=network_preflight(remaining,remaining_plan,paths(root)['raw_root'],paths(root)['output_root'])
    sequence=len(list(directory.glob(f'{batch_name(batch_id)}_resume_authorization_*.json')))+1
    name=f'{batch_name(batch_id)}_resume_authorization_{sequence:03}'
    record=dict(previous,authorization_code_head=head,authorization_utc=utc_now(),
        original_authorization_sha256=sha256_file(directory/f'{batch_name(batch_id)}_execution_authorization.json'),
        previous_authorization_code_head=previous['authorization_code_head'],
        resume_reason='Explicit continuation of the same frozen batch after a stopped execution',
        completed_subjects_reverified=[s for s in plan['subject_ids'] if s in completed],
        unresolved_subject_ids=remaining_ids,
        resume_network_preflight=report,environment_preflight=environment)
    if network_policy is not None:
        record.update(network_wait_policy=network_policy, network_wait_policy_sha256=canonical_hash(network_policy),
            autonomous_starting_state_sha256=sha256_file(runtime_directory(root)/f'{batch_name(batch_id)}_autonomous_starting_state.json'),
            partial_prefixes=report['partial_prefixes'], prohibit_batch_005=True)
    write_json(directory/f'{name}.json',record)
    return record


def directory_bytes(path):
    return sum(f.stat().st_size for f in Path(path).rglob('*') if f.is_file())


