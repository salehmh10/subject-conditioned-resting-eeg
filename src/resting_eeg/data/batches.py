GIB = 1073741824
ACCESS_SHA = 'd04b43f1ebe32bf41293d14e7c2f034e03c567ed0063350630aa81410e2500d4'


def cap_bytes(gib):
    try:
        value = Decimal(str(gib)) * GIB
    except InvalidOperation as exc:
        raise ValueError('Explicit positive GiB cap required') from exc
    if not value.is_finite() or value <= 0 or value != value.to_integral_value():
        raise ValueError('GiB cap must represent a positive exact integer byte count')
    return int(value)


def batch_name(batch_id):
    if not re.fullmatch(r'[0-9]{3}', str(batch_id)) or int(batch_id) < 1:
        raise ValueError('Batch ID must be three digits, starting at 001')
    return f'batch_{batch_id}'


def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def read_journal(path):
    path = Path(path)
    return [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines()] if path.exists() else []


def csv_write(path, frame):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + '.tmp')
    with temp.open('w', encoding='utf-8', newline='') as handle:
        frame.to_csv(handle, index=False, lineterminator='\n')
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temp, path)


